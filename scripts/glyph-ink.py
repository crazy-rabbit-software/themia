"""
Generate the icon font's ink table ([S-14240]) from Segoe Fluent Icons itself.

A FontIcon draws its glyph in a box of its font size, the font's em (Segoe Fluent Icons: ascent 2048, descent 0, an
em of 2048 units), but most glyphs ink only part of it: the memory chip leaves an eighth over and under, the drive a
flat bar through the middle, the battery a third over and under. A readout that stands its lead glyph's box on the
card's inset leaves that room as a band the owner sees (WR-1, WR-3, WR-4); the table says where each glyph's ink is.

Reads the font's outlines (fontTools) for every private-use code point (U+E700..U+F8FF) and writes
src/Themia.Sdk/Kit/Family/GlyphInk.g.cs: per glyph the left, top, right and bottom of its ink in font units from the
em box's top left. A glyph that inks its whole box (or has no outline) is left out: the reader takes the whole box.

Run after Windows updates the font:
    python scripts/glyph-ink.py [path to SegoeIcons.ttf]
The generated file is checked in; the build does not run this.
"""

import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont

DEFAULT_FONT = r"C:\Windows\Fonts\SegoeIcons.ttf"
OUT = Path(__file__).resolve().parent.parent / "src" / "Themia.Sdk" / "Kit" / "Family" / "GlyphInk.g.cs"
FIRST, LAST = 0xE700, 0xF8FF
PER_LINE = 4


def main() -> None:
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_FONT
    font = TTFont(path)
    em = font["head"].unitsPerEm
    ascent = font["hhea"].ascent
    if em != 2048 or ascent != 2048 or font["hhea"].descent != 0:
        sys.exit(f"Unexpected metrics (em {em}, ascent {ascent}, descent {font['hhea'].descent}): the table assumes "
                 "the glyph's box is its em, ascent 2048 and descent 0.")

    glyphs = font.getGlyphSet()
    rows = []
    for code, name in sorted(font.getBestCmap().items()):
        if not FIRST <= code <= LAST:
            continue
        pen = BoundsPen(glyphs)
        glyphs[name].draw(pen)
        if pen.bounds is None:
            continue
        x_min, y_min, x_max, y_max = (round(v) for v in pen.bounds)
        box = (x_min, ascent - y_max, x_max, ascent - y_min)
        if box[0] <= 0 and box[1] <= 0 and box[2] >= em and box[3] >= em:
            continue
        rows.append((code, *box))

    version = font["name"].getDebugName(5) or "unknown version"
    lines = [
        "// <auto-generated>",
        f"// Generated by scripts/glyph-ink.py from Segoe Fluent Icons (SegoeIcons.ttf, {version}).",
        "// Do not edit by hand: run the script again.",
        "// </auto-generated>",
        "",
        "namespace Themia.Sdk.Kit;",
        "",
        "public static partial class GlyphInk",
        "{",
        "    /// <summary>The em the table's units are of (Segoe Fluent Icons' units per em, its ascent; descent 0).</summary>",
        f"    private const double Em = {em};",
        "",
        "    /// <summary>",
        f"    /// Every private-use glyph of the font that does not ink its whole em box ({len(rows)}), in code-point order: its code",
        "    /// point, then the left, top, right and bottom of its ink in font units from the box's top left.",
        "    /// </summary>",
        "    private static readonly int[] Data =",
        "    [",
    ]
    for i in range(0, len(rows), PER_LINE):
        chunk = rows[i:i + PER_LINE]
        lines.append("        " + " ".join(f"0x{c:04X}, {l}, {t}, {r}, {b}," for c, l, t, r, b in chunk))
    lines += ["    ];", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(rows)} glyphs")


if __name__ == "__main__":
    main()
