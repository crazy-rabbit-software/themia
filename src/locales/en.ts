// Locale type: same nested key structure as English, but every leaf is a
// plain string (translations differ from the English literal values). Locale
// files annotate with `: Messages` so TS enforces key/shape parity without
// demanding the value equal the English literal.
type Stringify<T> = { [K in keyof T]: T[K] extends string ? string : Stringify<T[K]> };
export type Messages = Stringify<typeof en>;

// issue #91: every shipped locale is now COMPLETE and annotated `: Messages`,
// so adding a key here fails the build until all nine are translated. The old
// `PartialMessages` deep-partial is gone deliberately: it let a locale silently
// omit a key and fall back to English, which is exactly how de/es/fr/it/pt/pl/ja
// drifted to ~50% coverage without any test noticing. `t()` still falls back at
// runtime (see i18n.ts) — that is the safety net for a corrupt build, not the
// normal path.
